// Helper function to get unique values for filters
export const getUniqueCareerFields = (companies = sampleCompanies) => {
  const fields = new Set();
  companies?.forEach(company => {
    company?.careerFields?.forEach(field => fields.add(field));
  });
  return Array.from(fields).sort();
};

export const getUniqueRegions = (companies = sampleCompanies) => {
  const regions = new Set(companies?.map(c => c?.region).filter(Boolean));
  return Array.from(regions).sort();
};

export const getUniqueProvinces = (companies = sampleCompanies) => {
  const provinces = new Set(companies?.map(c => c?.province).filter(Boolean));
  return Array.from(provinces).sort();
};

